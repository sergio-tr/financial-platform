from __future__ import annotations

import re

from . import codes
from .codes import TraceError

BRANCH_RE = re.compile(r"^(feature|bugfix|chore)/SER-([1-9][0-9]*)-[a-z0-9]+(?:-[a-z0-9]+)*$")

# Hard-forbidden contribution trailers / generated markers (any metadata text).
FORBIDDEN_TRAILER = re.compile(
    r"(?i)(\bCo-authored-by\b|\bGenerated by\b|\bGenerated-with\b|\bGenerated-By\b)"
)

# Assistant/product names as contribution attribution — branch/title/commit subject only.
FORBIDDEN_ASSISTANT_NAME = re.compile(r"(?i)\b(Cursor|ChatGPT|Claude|Copilot)\b")

CONVENTIONAL_SUBJECT = re.compile(
    r"^(feat|fix|chore|refactor|docs|test|build|ci|perf|style)(\([a-z0-9/_-]+\))?: .+"
)


def parse_branch_ser(branch: str) -> str | None:
    m = BRANCH_RE.fullmatch(branch)
    if not m:
        return None
    return f"SER-{m.group(2)}"


def validate_branch(branch: str) -> list[TraceError]:
    if BRANCH_RE.fullmatch(branch):
        return []
    return [TraceError(codes.TRACE_BRANCH_INVALID, branch)]


def validate_contribution_metadata(
    *texts: str,
    check_assistant_names: bool = False,
) -> list[TraceError]:
    errors: list[TraceError] = []
    for text in texts:
        if not text:
            continue
        if FORBIDDEN_TRAILER.search(text):
            errors.append(TraceError(codes.TRACE_FORBIDDEN_CONTRIBUTION_ATTRIBUTION, text[:160]))
            continue
        if check_assistant_names and FORBIDDEN_ASSISTANT_NAME.search(text):
            errors.append(TraceError(codes.TRACE_FORBIDDEN_CONTRIBUTION_ATTRIBUTION, text[:160]))
    return errors


def validate_conventional_subject(subject: str) -> list[TraceError]:
    if CONVENTIONAL_SUBJECT.fullmatch(subject.strip()):
        return []
    return [TraceError(codes.TRACE_BRANCH_INVALID, f"commit subject not Conventional Commit: {subject!r}")]


def is_legacy_pr1_exception(pr_number: int | None, branch: str | None) -> bool:
    """SER-96 §15 / R37-18 — exact historical exception only."""
    return pr_number == 1 and branch == "feature/documentation-governance"
